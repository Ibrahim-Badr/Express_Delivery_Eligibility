from __future__ import annotations

from datetime import date, datetime
from typing import Any, Dict, List, Optional

import pandas as pd
from sqlalchemy import Column, Date, Float, Integer, String
from sqlalchemy.orm import Session, sessionmaker

from src.core.config import settings
from src.domain.entities import OrderEntity
from src.etl.cleaning import clean_orders_data, validate_dataset
from src.etl.features import dataframe_to_training_entities
from src.infra.abstractions.order_repository import OrderRepository
from src.infra.database.database import Base, SessionLocal, engine
from src.ml.data_generation import generate_orders_dataset


class OrderRecord(Base):
    """SQLAlchemy model for the ERP `orders` table."""

    __tablename__ = "orders"

    order_id = Column(String(64), primary_key=True, index=True)
    order_date = Column(Date, nullable=True)
    hour = Column(Integer, nullable=False)
    day_of_week = Column(Integer, nullable=False)
    weekend = Column(Integer, nullable=True)  # Nullable before 2015-07-01
    distance_km = Column(Float, nullable=False)
    order_value_eur = Column(Float, nullable=False)
    weight_kg = Column(Float, nullable=False)
    stock_available = Column(Integer, nullable=False)
    preparation_time_min = Column(Float, nullable=True)  # Nullable before 2017-07-01
    carrier_capacity = Column(Float, nullable=False)
    weather = Column(String(64), nullable=False)
    delivery_zone = Column(String(64), nullable=False)
    customer_type = Column(String(64), nullable=False)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "order_id": self.order_id,
            "order_date": self.order_date.isoformat() if self.order_date else None,
            "hour": self.hour,
            "day_of_week": self.day_of_week,
            "weekend": self.weekend,
            "distance_km": self.distance_km,
            "order_value_eur": self.order_value_eur,
            "weight_kg": self.weight_kg,
            "stock_available": self.stock_available,
            "preparation_time_min": self.preparation_time_min,
            "carrier_capacity": self.carrier_capacity,
            "weather": self.weather,
            "delivery_zone": self.delivery_zone,
            "customer_type": self.customer_type,
        }


class PostgresOrderRepository(OrderRepository):
    """PostgreSQL implementation of OrderRepository.

    Connects to the operational production orders table generated by the ERP.
    Handles upsert operations, querying, and extracts cleaned training data
    processed through the ETL cleaning pipeline.
    """

    def __init__(
        self,
        db_engine=None,
        session_factory: Optional[sessionmaker[Session]] = None,
    ):
        self._engine = db_engine or engine
        self._session_factory = session_factory or SessionLocal
        Base.metadata.create_all(bind=self._engine)

    def save(self, order_id: str, order_data: Dict[str, Any]) -> None:
        """Upsert an order record in PostgreSQL."""
        db: Session = self._session_factory()
        try:
            order_date_raw = order_data.get("order_date")
            parsed_date: Optional[date] = None
            if isinstance(order_date_raw, date):
                parsed_date = order_date_raw
            elif isinstance(order_date_raw, str) and order_date_raw:
                try:
                    parsed_date = datetime.fromisoformat(order_date_raw.split("T")[0]).date()
                except ValueError:
                    parsed_date = None

            record = OrderRecord(
                order_id=order_id,
                order_date=parsed_date,
                hour=int(order_data["hour"]),
                day_of_week=int(order_data["day_of_week"]),
                weekend=(
                    int(order_data["weekend"]) if order_data.get("weekend") is not None else None
                ),
                distance_km=float(order_data["distance_km"]),
                order_value_eur=float(order_data["order_value_eur"]),
                weight_kg=float(order_data["weight_kg"]),
                stock_available=int(order_data["stock_available"]),
                preparation_time_min=(
                    float(order_data["preparation_time_min"])
                    if order_data.get("preparation_time_min") is not None
                    else None
                ),
                carrier_capacity=float(order_data["carrier_capacity"]),
                weather=str(order_data["weather"]),
                delivery_zone=str(order_data["delivery_zone"]),
                customer_type=str(order_data["customer_type"]),
            )
            db.merge(record)
            db.commit()
        finally:
            db.close()

    def get(self, order_id: str) -> Optional[Dict[str, Any]]:
        """Retrieve an order by ID, returning a dictionary or None."""
        db: Session = self._session_factory()
        try:
            record = (
                db.query(OrderRecord)
                .filter(OrderRecord.order_id == order_id)
                .first()
            )
            if record:
                return record.to_dict()
            return None
        finally:
            db.close()

    def get_all(self, limit: Optional[int] = None) -> List[Dict[str, Any]]:
        """Retrieve stored orders up to the given limit."""
        db: Session = self._session_factory()
        try:
            query = db.query(OrderRecord)
            if limit is not None:
                query = query.limit(limit)
            records = query.all()
            return [record.to_dict() for record in records]
        finally:
            db.close()

    def count(self) -> int:
        """Return total order count."""
        db: Session = self._session_factory()
        try:
            return db.query(OrderRecord).count()
        finally:
            db.close()

    def get_training_data(self) -> tuple[list[OrderEntity], list[int]]:
        """Extract training data from PostgreSQL, clean, impute, and return entities with labels."""
        raw_orders = self.get_all()

        if raw_orders:
            df = pd.DataFrame(raw_orders)
        else:
            df = generate_orders_dataset(random_state=settings.random_seed)

        df_clean = clean_orders_data(df)
        validate_dataset(df_clean)
        return dataframe_to_training_entities(df_clean)


__all__ = ["OrderRecord", "PostgresOrderRepository"]
